"""Convert progress/task6_report_draft.md to LaTeX, then make it pdflatex-safe.

Run it from the repository root:

    python docs/make_report.py

It writes Assignment2_Report_24101322D_HUANG_Haoran.tex next to the
repository root, and the PDF is produced with:

    pdflatex Assignment2_Report_24101322D_HUANG_Haoran.tex


Three adjustments are made to the markdown before conversion:

  1. The line "## PolyU Main Campus Image Classification" is removed from the
     body, because it is the subtitle and belongs on the title page.
  2. Headings are shifted down one level, so "## 1. Introduction" becomes a
     section and "### 1.1 ..." becomes a subsection. Section numbers are NOT
     generated by LaTeX: the numbers written in the headings are the ones the
     report's own cross references use, so they are kept literally.

After conversion the .tex is post-processed for pdflatex:

  - the CJK runs are wrapped in a CJKutf8 environment, because the report
    quotes two Chinese signs;
  - the single rightwards arrow is replaced by a math arrow.
"""
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path("/mnt/d/Program Files/learn_torch/python-cv/Assignment2")
SRC = REPO / "progress" / "task6_report_draft.md"
TEMPLATE = REPO / "docs" / "report_template.tex"
OUT_TEX = REPO / "Assignment2_Report_24101322D_HUANG_Haoran.tex"
# pandoc is not on PATH by default. Point PANDOC at the binary, or install
# pandoc and set PANDOC = "pandoc".
PANDOC = os.environ.get("PANDOC", "pandoc")
if not shutil.which(PANDOC):
    for candidate in sorted(Path("/tmp/pdfenv").rglob("pandoc")):
        if candidate.is_file() and os.access(candidate, os.X_OK):
            PANDOC = str(candidate)
            break

CJK = r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]"

md = SRC.read_text(encoding="utf-8")

before = md
md = md.replace("## PolyU Main Campus Image Classification\n", "", 1)
if md == before:
    print("ABORTED: subtitle line not found")
    sys.exit(1)

# The name, student number, course, deadline and the dataset link are written
# into the title page by the template, so the same block has to come out of
# the body or it appears twice.
_header = re.compile(
    r"\n\*\*Name:\*\*.*?"
    r"The link is shared as \"anyone with the link\", so no sign-in is needed\.\n",
    re.S,
)
md, n = _header.subn("\n", md, count=1)
if n != 1:
    print("ABORTED: title metadata block not found")
    sys.exit(1)

tmp_md = Path("/tmp/report_body.md")
tmp_md.write_text(md, encoding="utf-8")

cmd = [
    PANDOC, str(tmp_md),
    "--from", "markdown+pipe_tables+raw_tex",
    "--to", "latex",
    "--template", str(TEMPLATE),
    "--standalone",
    "--wrap=preserve",
    "--shift-heading-level-by=-1",
    "--resource-path", f"{REPO}:{REPO / 'docs'}",
    "-o", str(OUT_TEX),
]
res = subprocess.run(cmd, capture_output=True, text=True)
if res.returncode != 0:
    print("PANDOC FAILED")
    print(res.stdout[-3000:])
    print(res.stderr[-3000:])
    sys.exit(1)

tex = OUT_TEX.read_text(encoding="utf-8")

# --- merge the two captions --------------------------------------------
# pandoc turns the image alt text into a \caption, and the markdown also
# carries a hand written "Figure N. ..." line. Both would print. The hand
# written one is the richer text, so it becomes the caption and the separate
# italic line is dropped.
_fig_re = re.compile(
    r"\\begin\{figure\}\s*\n\s*\\centering\s*\n"
    r"(?P<img>(?:.|\n)*?)\\caption\{(?P<short>[^{}]*)\}\s*\n"
    r"\\end\{figure\}"
)
_emph_re = re.compile(r"\\emph\{(Figure \d+\. .*?)\}\n", re.S)

captions = _emph_re.findall(tex)
figures = list(_fig_re.finditer(tex))
if len(captions) != len(figures):
    print(f"ABORTED: {len(figures)} figures but {len(captions)} hand written captions")
    sys.exit(1)

used = [0]


def _replace_figure(match):
    idx = used[0]
    used[0] += 1
    full = captions[idx]
    full = re.sub(r"^Figure \d+\.\s*", "", full)
    return (
        "\\begin{figure}\n\\centering\n"
        + match.group("img")
        + "\\caption{" + full + "}\n"
        + "\\end{figure}"
    )


tex = _fig_re.sub(_replace_figure, tex)

# drop the now duplicated italic caption lines
for cap in captions:
    tex = tex.replace("\\emph{" + cap + "}\n", "", 1)

# --- let long file names break inside \texttt ----------------------------
# A monospaced file name is one unbreakable box, so a table cell holding
# docs/figures/figure1_inside_locations_annotated.png runs off the page.
# Allow a line break after each underscore, hyphen and slash inside those
# boxes only.
def _breakable(match):
    body = match.group(1)
    body = body.replace("\\_", "\\_\\allowbreak{}")
    body = body.replace("-", "-\\allowbreak{}")
    body = body.replace("/", "/\\allowbreak{}")
    return "\\texttt{" + body + "}"

tex = re.sub(r"\\texttt\{((?:[^{}]|\{[^{}]*\})*)\}", _breakable, tex)

# --- wrap the CJK runs -------------------------------------------------
cjk_runs = re.findall(CJK + r"+", tex)
tex = re.sub(CJK + r"+", lambda m: "\\begin{CJK*}{UTF8}{gbsn}" + m.group(0) + "\\end{CJK*}", tex)

# --- the arrow --------------------------------------------------------
tex = tex.replace("→", "\\ensuremath{\\rightarrow}")

OUT_TEX.write_text(tex, encoding="utf-8")

print(f"wrote {OUT_TEX.name}  ({len(tex.splitlines())} lines, {len(tex)} bytes)")
print("includegraphics:", re.findall(r'\\includegraphics(?:\[[^\]]*\])?\{([^}]*)\}', tex))
print("sections:", len(re.findall(r'\\section\{', tex)),
      "subsections:", len(re.findall(r'\\subsection\{', tex)),
      "tables:", len(re.findall(r'\\begin\{longtable\}', tex)))
print(f"CJK runs wrapped: {len(cjk_runs)}  ->  {cjk_runs}")
print("remaining raw CJK outside CJK env:",
      len(re.findall(CJK, re.sub(r"\\begin\{CJK\*\}.*?\\end\{CJK\*\}", "", tex, flags=re.S))))
print("remaining raw arrow:", tex.count("→"))
